//! Compile the frontend into the binary (D7).
//!
//! `ui/dist` is committed, so `cargo install` and the release need a Rust toolchain
//! and nothing else, and CI fails a pull request whose committed bundle is not what
//! its sources build. This script only embeds it.
//!
//! It never runs npm. ai-planner's build script rebuilds the bundle when node is
//! present and a source looks newer, which on a CI or release runner - node is
//! preinstalled on both - means `npm ci` fetching packages from inside `cargo build`,
//! decided by checkout mtimes. Building the frontend is `npm run build` in `ui/`.

use std::path::{Path, PathBuf};

fn main() {
    let dist = Path::new(&env("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("the crate sits two levels below the repo root")
        .join("ui/dist");
    println!("cargo:rerun-if-changed={}", dist.display());

    let files = collect(&dist).unwrap_or_default();
    if files.is_empty() {
        // A clear message at build time beats a blank page at run time.
        println!(
            "cargo:warning=no frontend bundle at {} - `ailocal ui` will serve a \
             placeholder. Run `npm ci && npm run build` in ui/ to fix it.",
            dist.display()
        );
    }

    let out = PathBuf::from(env("OUT_DIR")).join("assets.rs");
    std::fs::write(&out, render(&files)).expect("writing the asset table");
}

fn env(key: &str) -> String {
    std::env::var(key).unwrap_or_else(|_| panic!("cargo sets {key}"))
}

/// Every file under `dist`, as (url path, mime, absolute source path).
fn collect(dist: &Path) -> std::io::Result<Vec<(String, &'static str, PathBuf)>> {
    let mut files = Vec::new();
    let mut stack = vec![dist.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir)? {
            let path = entry?.path();
            if path.is_dir() {
                println!("cargo:rerun-if-changed={}", path.display());
                stack.push(path);
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            let relative = path
                .strip_prefix(dist)
                .expect("walked from dist")
                .to_string_lossy()
                .replace('\\', "/");
            files.push((relative, mime(&path), path.canonicalize()?));
        }
    }
    // Sorted so the generated file is stable, and a rebuild that changes nothing
    // produces no diff.
    files.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(files)
}

fn mime(path: &Path) -> &'static str {
    match path.extension().and_then(|e| e.to_str()) {
        Some("html") => "text/html; charset=utf-8",
        Some("js") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json" | "map") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("ico") => "image/x-icon",
        Some("woff2") => "font/woff2",
        _ => "application/octet-stream",
    }
}

fn render(files: &[(String, &'static str, PathBuf)]) -> String {
    let mut out = String::from(
        "// Generated by build.rs. The bundle, compiled in.\n\
         pub static ASSETS: &[(&str, &str, &[u8])] = &[\n",
    );
    for (path, mime, source) in files {
        out.push_str(&format!(
            "    ({path:?}, {mime:?}, include_bytes!({:?})),\n",
            source.display().to_string()
        ));
    }
    out.push_str("];\n");
    out
}
